#!/usr/bin/env python3
"""Generate keccak_f_flat.sv — keccak_f.sv with every user-function call expanded
inline. Same design, same results; the only difference is that no process contains a
`Terminator::Call`, which is what vita's bytecode VM allow-list rejects. Used to size
the VM-coverage lever in doc-18 round-26."""
RHO = [0,1,62,28,27, 36,44,6,55,20, 3,10,43,25,39, 41,45,15,21,8, 18,2,61,56,14]
RC = ["0000000000000001","0000000000008082","800000000000808a","8000000080008000",
      "000000000000808b","0000000080000001","8000000080008081","8000000000008009",
      "000000000000008a","0000000000000088","0000000080008009","000000008000000a",
      "000000008000808b","800000000000008b","8000000000008089","8000000000008003",
      "8000000000008002","8000000000000080","000000000000800a","800000008000000a",
      "8000000080008081","8000000000008080","0000000080000001","8000000080008008"]
def rot(e, n): return e if n == 0 else f"(({e} << {n}) | ({e} >> {64-n}))"
L = ["""// GENERATED by gen_flat.py -- do not edit. See keccak_f.sv for the readable form.
module keccak_f (
    input  wire          clk,
    input  wire          rst_n,
    input  wire          start,
    input  wire [1599:0] din,
    output reg  [1599:0] dout,
    output reg           done
);
    reg [63:0] st [0:24];
    reg [4:0]  rnd;
    reg        busy;
    integer x;
    reg [63:0] c [0:4];
    reg [63:0] d [0:4];
    reg [63:0] a [0:24];
    reg [63:0] b [0:24];
    reg [63:0] rcv;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            busy <= 1'b0; done <= 1'b0; rnd <= 5'd0;
            for (x = 0; x < 25; x = x + 1) st[x] <= 64'd0;
        end else begin
            done <= 1'b0;
            if (start && !busy) begin
                for (x = 0; x < 25; x = x + 1) st[x] <= din[64*x +: 64];
                rnd  <= 5'd0;
                busy <= 1'b1;
            end else if (busy) begin"""]
for x in range(5):
    L.append(f"                c[{x}] = st[{x}] ^ st[{x+5}] ^ st[{x+10}] ^ st[{x+15}] ^ st[{x+20}];")
for x in range(5):
    L.append(f"                d[{x}] = c[{(x+4)%5}] ^ {rot(f'c[{(x+1)%5}]', 1)};")
for y in range(5):
    for x in range(5):
        L.append(f"                a[{x+5*y}] = st[{x+5*y}] ^ d[{x}];")
for y in range(5):
    for x in range(5):
        L.append(f"                b[{y+5*((2*x+3*y)%5)}] = {rot(f'a[{x+5*y}]', RHO[x+5*y])};")
for y in range(5):
    for x in range(5):
        L.append(f"                a[{x+5*y}] = b[{x+5*y}] ^ ((~b[{((x+1)%5)+5*y}]) & b[{((x+2)%5)+5*y}]);")
L.append("                case (rnd)")
for i, v in enumerate(RC):
    L.append(f"                    5'd{i}: rcv = 64'h{v};")
L.append("                    default: rcv = 64'd0;\n                endcase")
L.append("                a[0] = a[0] ^ rcv;")
L.append("""                for (x = 0; x < 25; x = x + 1) st[x] <= a[x];
                if (rnd == 5'd23) begin
                    busy <= 1'b0;
                    done <= 1'b1;
                    for (x = 0; x < 25; x = x + 1) dout[64*x +: 64] <= a[x];
                end else begin
                    rnd <= rnd + 5'd1;
                end
            end
        end
    end
endmodule""")
open("keccak_f_flat.sv", "w").write("\n".join(L) + "\n")
