//! §5.2 Q-MDRVMIX C1 + C2: rules X and Y (`elaborate/src/mdrv_mix.rs`) — a variable of the target set (a module-level `logic` / `reg` /
//! `bit`, internal or output, not type-parameter-typed: the view's declaration fact) whose continuous writer (an `assign`, a
//! gate output, an instance port) and procedural writer (a blocking or non-blocking statement of `always_comb`, `always_ff`,
//! `always_latch`, `always`, `initial`, a declaration initializer, a subroutine inlined into one, or a frame body) write
//! overlapping decided bits is E3001 (rule X, C1) ; so is an `always_comb`'s own blocking or non-blocking statement and another
//! process's (`always_comb`, `always_ff`, `always_latch`, `always`, `initial`, its own text or a static task it inlines) on
//! overlapping decided bits (rule Y, C2 ; IEEE 1800-2017 §9.2.2.2), one E3001 per variable, rule X first. The whole stdout,
//! stderr and exit code of `vita t.sv`, as POST prints them:
//! - LOUD pins (rules X and Y): the doc carries PRE's text (`W/wrext/build/bin2/vita-post`, md5 aa1604e9), the IEEE clause with its
//!   line in `W/ref/ieee1800-2017.txt`, and each oracle's line (iverilog 13.0 -g2012 compile / vvp, verilator 5.054
//!   --lint-only -Wall ; "an ERROR" / "lint WARNING" says which) ;
//! - QUIET pins: POST prints PRE's text ; the doc says why the rule does not fire (outside the target set, not a writer,
//!   no overlap, an older check already reported the variable, or a named residue).
//!
//! Cells: W/mdrv/ground/cells/m (matrix), W/mdrv/premise/cells and premise/k7 (judge 1, the K7 twins), W/mdrv/premise2/cells
//! (judge 2), W/mdrv/plan2/probe/cells, W/mdrv/plan/probe, W/mdrv/build/pins/new and new2 (C2) ; generated by W/mdrv/build/pins/gen_pins.py.
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

static NEXT: AtomicU64 = AtomicU64::new(0);

/// (stdout, stderr, exit code) of `vita t.sv` in a temp dir of its own.
fn run(src: &str) -> (String, String, Option<i32>) {
    let n = NEXT.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir().join(format!("vita_mdrv_mix_pins_{}_{n}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("t.sv"), src).unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_vita"))
        .arg("t.sv")
        .current_dir(&dir)
        .output()
        .expect("run vita");
    let _ = std::fs::remove_dir_all(&dir);
    (
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
        out.status.code(),
    )
}

fn check(id: &str, src: &str, want_stdout: &str, want_stderr: &str, want_rc: i32) {
    let (so, se, rc) = run(src);
    assert_eq!(so, want_stdout, "{id}: stdout");
    assert_eq!(se, want_stderr, "{id}: stderr");
    assert_eq!(rc, Some(want_rc), "{id}: exit code");
}

